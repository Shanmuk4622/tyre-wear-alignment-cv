def budget_md(archs, folds=3, seeds=3, extra=""):
    ids = [f"a-{a}-base-f{f}-s{s}" for a in archs for f in range(folds) for s in range(seeds)]
    tot_h = sum(T.cost_of(i) for i in ids) / 60
    rows = "\n".join(
        f"| `{a}` | {T.ZOO[a]['res']} | {T.ZOO[a]['bs']} | {T.RECIPE['max_epochs']} | "
        f"{T.STATIC_COST_HINTS.get(a, T.DEFAULT_COST):.0f} min | "
        f"{T.STATIC_COST_HINTS.get(a, T.DEFAULT_COST)*folds*seeds/60:.1f} h |"
        for a in archs)
    wall = "\n".join(
        f"| {nw} | ~{T.estimate_phase(ids, nw)['wall_clock_hours']:.1f} h | "
        f"{T.estimate_phase(ids, nw)['sessions_needed']} |"
        for nw in (1, 2, 4) if nw <= len(ids))
    return f"""
## What this notebook runs

| | |
|---|---|
| **Architectures** | {len(archs)} |
| **Folds x seeds each** | {folds} x {seeds} = {folds*seeds} |
| **Total training runs** | **{len(ids)}** |
| **Estimated GPU time** | **~{tot_h:.0f} GPU-hours** |

### Wall-clock, by how many Kaggle accounts you run

| NUM_WORKERS | Wall-clock | Kaggle sessions each |
|---|---|---|
{wall}

### Per architecture

| Architecture | Res | Batch | Epochs | Est. per run | x {folds*seeds} runs |
|---|---|---|---|---|---|
{rows}

> Estimates come from a **static** cost table calibrated against measured T4
> throughput. It stays static on purpose: if measurements fed back into the
> work split, two workers planning at different times would disagree about
> what they own, and a job gets trained twice while another is abandoned.

> **No early stopping.** Every run trains the full {T.RECIPE['max_epochs']}-epoch budget. Equal
> budget for every architecture is what keeps the comparison fair, and it means
> a run's length is known in advance -- which is what makes the estimate above
> honest.

> A Kaggle session lasts ~9-12 h and this pipeline pauses cleanly at 8.5 h, so a
> run needing more than one session resumes automatically. Just start a fresh
> session and re-run the notebook.
{extra}
"""

