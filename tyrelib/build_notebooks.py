def md(s):   return {"cell_type": "markdown", "metadata": {}, "source": s.splitlines(True)}
def code(s): return {"cell_type": "code", "execution_count": None, "metadata": {},
                     "outputs": [], "source": s.splitlines(True)}

def write_nb(name, cells):
    nb = {"cells": cells,
          "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                       "language_info": {"name": "python", "version": "3.11.13"},
                       "accelerator": "GPU",
                       "kaggle": {"accelerator": "nvidiaTeslaT4",
                                  "dataSources": [{"sourceType": "datasetVersion",
                                                   "reference": "shanmuk4622/tire-dataset-prepared"}],
                                  "isGpuEnabled": True, "isInternetEnabled": True,
                                  "language": "python", "sourceType": "notebook"}},
          "nbformat": 4, "nbformat_minor": 5}
    p = OUT / name
    p.write_text(json.dumps(nb, indent=1))
    # verify the blob round-trips byte-identically -- a silent truncation here
    # means you debug the wrong code for an hour
    blob = "".join(json.loads(p.read_text())["cells"][1]["source"])
    lit = blob.split("_LIB = (")[1].split(")\n")[0]
    got = base64.b64decode("".join(eval("(" + lit + ")")))
    assert got == LIB.read_bytes(), f"BASE64 ROUND-TRIP FAILED in {name}"
    print(f"  {name:<34} {p.stat().st_size/1024:6.0f} KB  {len(cells):2d} cells  b64 OK")

