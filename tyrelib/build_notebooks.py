def colour_feats(p):
    a = np.asarray(Image.open(p).convert('RGB').resize((64, 64)), np.float32) / 255.
    mx, mn = a.max(2), a.min(2)
    sat = np.where(mx > 0, (mx - mn) / (mx + 1e-6), 0)
